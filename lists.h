#ifndef LISTS_H
#define LISTS_H

// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
// Описи структур даних (Лабораторна робота 2.5, Варіант 3)
// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

// Вузол односпрямованого списку (1-й список)
struct SinglyNode
{
    char        cData;   // Інформаційне поле (символьне значення)
    SinglyNode* pNext;   // Вказівник на наступний елемент списку
};

// Вузол двоспрямованого списку (2-й список)
struct DoublyNode
{
    char        cData;   // Інформаційне поле (символьне значення)
    DoublyNode* pPrev;   // Вказівник на попередній елемент списку
    DoublyNode* pNext;   // Вказівник на наступний елемент списку
};

// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
// Відкриті підпрограми (inline)
// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

// Перевірка на рівність нулю вказівника на наступний елемент (односпрямований список)
inline bool isNextNull(const SinglyNode* pNode)
{
    return pNode == nullptr || pNode->pNext == nullptr;
}

// Перевірка на рівність нулю вказівника на наступний елемент (двоспрямований список)
inline bool isNextNull(const DoublyNode* pNode)
{
    return pNode == nullptr || pNode->pNext == nullptr;
}

#endif // LISTS_H
